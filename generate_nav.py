LOWERCASE_WORDS = {"and", "or", "for", "in", "on", "to", "with", "of", "via", "vs", "a", "the"}


# ---------------------------------------------------------------------------
# Labels and page metadata
# ---------------------------------------------------------------------------
def format_label(raw_name: str) -> str:
    """Convert a filename or directory slug into a clean human-readable title."""
    stem = re.sub(r"\.md$", "", raw_name, flags=re.IGNORECASE)
    if stem.upper() == "README":
        return "Overview"

    # Separate trailing version numbers attached to words like fedora44 -> fedora 44
    stem = re.sub(r"([a-zA-Z])(\d+)$", r"\1 \2", stem)
    words = re.split(r"[-_\s]+", stem.strip())

    formatted = []
    for i, word in enumerate(words):
        if not word:
            continue
        low = word.lower()
        if low in ACRONYMS:
            formatted.append(ACRONYMS[low])
        elif i > 0 and low in LOWERCASE_WORDS:
            formatted.append(low)
        else:
            formatted.append(word[:1].upper() + word[1:])

    title = " ".join(formatted)
    title = title.replace("Cheatsheet", "Cheat Sheet")
    return title


_HEADING_RE = re.compile(r"^(#{1,6})\s+(.*?)\s*#*\s*$")
_EMOJI_RE = re.compile(r"[\U0001F000-\U0001FAFF☀-➿️]")


def _strip_md(text: str) -> str:
    text = re.sub(r"!\[[^\]]*\]\([^)]*\)", "", text)  # images
    text = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", text)  # links
    text = re.sub(r"[*_`]+", "", text)
    text = _EMOJI_RE.sub("", text)
    return re.sub(r"\s+", " ", text).strip()


def page_summary(path: Path) -> str:
    """Short description of a guide for overview listings.

    Uses the intro paragraph (text before the guide's first section heading),
    skipping lead-in lines that end in ':'. Falls back to a descriptive
    opening heading, then to nothing.
    """
    in_fence = False
    headings: list[str] = []
    paragraphs: list[str] = []
    current: list[str] = []

    def flush() -> None:
        if current:
            paragraphs.append(" ".join(current))
            current.clear()

    for raw in path.read_text(encoding="utf-8", errors="ignore").splitlines():
        line = raw.strip()
        if line.startswith(("```", "~~~")):
            flush()
            in_fence = not in_fence
            continue
        if in_fence:
            continue
        m = _HEADING_RE.match(line)
        if m:
            flush()
            headings.append(_strip_md(m.group(2)))
            if len(headings) > 1:
                break  # past the intro
            continue
        if not line or line.startswith(("---", "|", "<", ">", "!!!", "???", "- ", "* ", "1.")):
            flush()
            continue
        current.append(line)
    flush()

    text = ""
    for para in paragraphs:
        cleaned = _strip_md(para)
        if cleaned and not cleaned.endswith(":"):
            text = cleaned
            break
    if not text and headings:
        text = headings[0]
    if text:
        text = text[0].upper() + text[1:]
    if len(text) > 150:
        text = text[:147].rsplit(" ", 1)[0].rstrip(",.;:") + "…"
    return text


def promote_leading_heading(path: Path) -> bool:
    """If a guide has no H1 and opens with an H2, turn that H2 into the H1."""
    text = path.read_text(encoding="utf-8")
    if GENERATED_MARKER in text:
        return False
    in_fence = False
    first_heading_idx = None
    lines = text.splitlines(keepends=True)
    for i, line in enumerate(lines):
        s = line.strip()
        if s.startswith(("```", "~~~")):
            in_fence = not in_fence
            continue
        if in_fence:
            continue
        if s.startswith("# "):
            return False  # already has an H1
        if first_heading_idx is None and s.startswith("#"):
            first_heading_idx = i
    if first_heading_idx is None or not lines[first_heading_idx].lstrip().startswith("## "):
        return False
    lines[first_heading_idx] = lines[first_heading_idx].replace("## ", "# ", 1)
    path.write_text("".join(lines), encoding="utf-8")
    return True


# ---------------------------------------------------------------------------
# Folder scanning
# ---------------------------------------------------------------------------
def guide_files(directory: Path) -> list[Path]:
    return sorted(
        [
            f
            for f in directory.iterdir()
            if f.is_file()
            and f.suffix.lower() == ".md"
            and f.name.upper() not in {"README.MD", "INDEX.MD"}
        ],
        key=lambda p: p.name.lower(),
    )


def sub_dirs(directory: Path) -> list[Path]:
    return sorted(
        [
            d
            for d in directory.iterdir()
            if d.is_dir() and d.name not in EXCLUDE_DIRS and not d.name.startswith(".")
        ],
        key=lambda p: p.name.lower(),
    )


def count_guides(directory: Path) -> int:
    return len(guide_files(directory)) + sum(count_guides(d) for d in sub_dirs(directory))


# ---------------------------------------------------------------------------
# Generated pages
# ---------------------------------------------------------------------------
def _esc(text: str) -> str:
    return html.escape(text, quote=False).replace("[", "&#91;").replace("]", "&#93;")


def _card(title: str, desc: str, count: int, href: str) -> str:
    noun = "guide" if count == 1 else "guides"
    return (
        f'[<span class="kz-card__title">{_esc(title)}'
        f'<span class="kz-card__count">{count} {noun}</span></span>'
        f'<span class="kz-card__desc">{_esc(desc)}</span>]({href}){{ .kz-card }}'
    )


def _list_item(title: str, desc: str, href: str) -> str:
    desc_html = f'<span class="kz-list__desc">{_esc(desc)}</span>' if desc else ""
    return f'- [<span class="kz-list__title">{_esc(title)}</span>{desc_html}]({href})'


def _write_generated(path: Path, body: str) -> None:
    if path.exists() and GENERATED_MARKER not in path.read_text(encoding="utf-8"):
        print(f"Skipping {path}: it exists and was not generated by this script")
        return
    path.write_text(body, encoding="utf-8")


def write_home_page() -> None:
    folders = [d for d in sub_dirs(ROOT_DIR) if count_guides(d)]
    total = sum(count_guides(d) for d in folders)

    cards = [
        _card(format_label(d.name), FOLDER_DESCS.get(d.name, ""), count_guides(d), f"{d.name}/index.md")
        for d in folders
    ]

    body = f"""---
title: Home
hide:
  - navigation
  - toc
---

{GENERATED_MARKER}
<span class="kz-generated"></span>

<div class="kz-hero" markdown>

# {SITE_TITLE}

{SITE_TAGLINE}

<div class="kz-stats" markdown>
<span class="kz-stat"><strong>{total}</strong> guides</span>
<span class="kz-stat"><strong>{len(folders)}</strong> categories</span>
<span class="kz-stat kz-stat--keys">Press <strong>/</strong> to search</span>
</div>

</div>

## Browse by topic

<div class="kz-cards" markdown>

{(chr(10) * 2).join(cards)}

</div>
"""
    _write_generated(ROOT_DIR / "index.md", body)


def write_folder_page(directory: Path) -> None:
    title = format_label(directory.name)
    desc = FOLDER_DESCS.get(directory.name, "")
    parts = ["---", f'title: "{title}"', "hide:", "  - toc", "---", "", GENERATED_MARKER, '<span class="kz-generated"></span>', "", f"# {title}", ""]
    if desc:
        parts += [desc, ""]

    subs = [d for d in sub_dirs(directory) if count_guides(d)]
    if subs:
        parts += ['<div class="kz-cards" markdown>', ""]
        for d in subs:
            parts += [_card(format_label(d.name), FOLDER_DESCS.get(d.name, ""), count_guides(d), f"{d.name}/index.md"), ""]
        parts += ["", "</div>", ""]

    guides = guide_files(directory)
    if guides:
        if subs:
            parts += ["## Guides", ""]
        parts += ['<div class="kz-list" markdown>', ""]
        parts += [_list_item(format_label(g.name), page_summary(g), g.name) for g in guides]
        parts += ["", "</div>", ""]

    _write_generated(directory / "index.md", "\n".join(parts))

    for d in subs:
        write_folder_page(d)


# ---------------------------------------------------------------------------
# Navigation
# ---------------------------------------------------------------------------
def build_nav_lines(directory: Path, indent: int = 2) -> list[str]:
    """Recursively scan directories and build YAML nav lines."""
    lines: list[str] = []
    prefix = " " * indent

    if directory != ROOT_DIR:
        lines.append(f'{prefix}- {(directory / "index.md").as_posix()}')

    for md_file in guide_files(directory):
        rel_path = md_file.relative_to(ROOT_DIR).as_posix()
        label = format_label(md_file.name).replace('"', '\\"')
        lines.append(f'{prefix}- "{label}": {rel_path}')

    for subdir in sub_dirs(directory):
        if not count_guides(subdir):
            continue
        child_lines = build_nav_lines(subdir, indent + 4)
        section_label = format_label(subdir.name)
        lines.append(f'{prefix}- "{section_label}":')
        lines.extend(child_lines)

    return lines


def write_nav() -> None:
    if not MKDOCS_FILE.exists():
        raise FileNotFoundError("mkdocs.yml not found in current directory.")

    content = MKDOCS_FILE.read_text(encoding="utf-8")

    # Strip any previous nav: block at the end of mkdocs.yml
    content_without_nav = re.sub(
        r"\n*nav:\s*\n(?:[ \t]*-.*\n?)*", "\n", content, flags=re.MULTILINE
    ).rstrip()

    nav_lines = ["nav:", '  - "Home": index.md']
    nav_lines.extend(build_nav_lines(ROOT_DIR, indent=2))

    updated_content = content_without_nav + "\n\n" + "\n".join(nav_lines) + "\n"
    MKDOCS_FILE.write_text(updated_content, encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--build",
        action="store_true",
        help="also promote leading '## Title' headings to H1 (edits files; CI only)",
    )
    args = parser.parse_args()

    if args.build:
        promoted = sum(
            promote_leading_heading(p)
            for p in ROOT_DIR.rglob("*.md")
            if not any(part in EXCLUDE_DIRS or part.startswith(".") for part in p.parts[:-1])
            and p.name.upper() != "README.MD"
        )
        print(f"Promoted the opening heading to H1 in {promoted} guides")

    write_home_page()
    for d in sub_dirs(ROOT_DIR):
        if count_guides(d):
            write_folder_page(d)
    write_nav()
    print("Generated home page, folder overview pages and nav: section in mkdocs.yml")


if __name__ == "__main__":
    main()
